test_that("conpyro() works", {
  data("default_input")
  expect_snapshot(conpyro(default_input))
  rm(default_input, envir = .GlobalEnv)
})

test_that("conpyro() ws input priority works", {
  expect_identical(
    conpyro(default_input, ws = c(10, 30))$`Scenario 1`$`Wind Speed (km/h)`,
    seq(10, 30, 1)
  )
  expect_identical(
    conpyro(default_input, ws = 10)$`Scenario 1`$`Wind Speed (km/h)`,
    10
  )
  expect_identical(
    conpyro(
      cbind(
        default_input,
        ws_min = rep(10, times = 3),
        ws_max = rep(30, times = 3)
      )
    )$`Scenario 1`$`Wind Speed (km/h)`,
    seq(10, 30, 1)
  )
  expect_identical(
    conpyro(
      cbind(
        default_input,
        ws_min = rep(10, times = 3),
        ws_max = rep(30, times = 3),
        ws     = rep(10, times = 3)
      )
    )$`Scenario 1`$`Wind Speed (km/h)`,
    10
  )
})

test_that("conpyro() can handle NA input values", {
  df <- default_input
  df[1, 2] <- NA
  expect_identical(conpyro(df)$`Scenario 1`$`mcsa`, as.numeric(NA))
  df <- default_input
  df[1, 3] <- NA
  expect_identical(conpyro(df)$`Scenario 1`$`mcsa`, as.numeric(NA))
  df <- default_input
  df[1, 4] <- NA
  expect_identical(conpyro(df)$`Scenario 1`$`mcsa`, as.numeric(NA))
  rm(df)
})

